import sys
import uuid
import asyncio
import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent.parent.parent))
from core.config import CONFIG
from core.city.agent_base import AgentBase
from core.memory.episodic import EpisodicMemory
from core.memory.obsidian_sync import ObsidianSync
from core.loop.context_engine import ContextEngine
from loguru import logger

_CHAIRMAN = CONFIG["models"]["chairman"]


class JournalWriter(AgentBase):
    """
    Writes daily/weekly Obsidian journal entries from episodic events.
    Daily at 22:30, weekly review on Sunday 23:00.
    RULE 11: vector-chairman (local), not Claude API.
    """

    def __init__(self, generation: int = 1, ghost: dict | None = None):
        super().__init__(
            agent_id=str(uuid.uuid4()),
            name="JournalWriter",
            district="reflection",
            generation=generation,
        )
        if ghost:
            self.inherit_ghost(ghost)
        self._memory = EpisodicMemory()
        self._obsidian = ObsidianSync()
        self._context = ContextEngine()
        logger.info(f"[VECTOR][journal_writer] ready gen={generation}")

    def _fetch_events(self, hours: int = 24) -> list[dict]:
        cutoff = (datetime.datetime.now() - datetime.timedelta(hours=hours)).isoformat()
        try:
            cur = self._memory.conn.cursor()
            cur.execute(
                "SELECT event_type, content, tags, source, timestamp FROM episodic_memory "
                "WHERE timestamp > ? ORDER BY timestamp ASC",
                (cutoff,),
            )
            cols = [d[0] for d in cur.description]
            return [dict(zip(cols, r)) for r in cur.fetchall()]
        except Exception as e:
            logger.warning(f"[VECTOR][journal_writer] fetch failed: {e}")
            return []

    def _narrative(self, events: list[dict], hydration: str, entry_type: str) -> str:
        summary = "\n".join(
            f"[{e.get('timestamp','')[:16]}] {e.get('event_type','')}: {e.get('content','')[:100]}"
            for e in events[:80]
        )
        prompt = (
            f"You are writing a personal journal entry ({entry_type}) for Arghyadeep based on his activity.\n\n"
            f"Activity log ({len(events)} events):\n{summary}\n\n"
            "Write a reflective, personal journal entry in first person. Structure:\n"
            "**What happened** - key events and accomplishments\n"
            "**How I felt / what I noticed** - patterns, energy, focus\n"
            "**What I learned** - insights, realisations\n"
            "**Tomorrow's intention** - one clear focus\n\n"
            "Be concise, genuine, and specific."
        )
        try:
            from core.inference.ollama_safe import chat
            text = chat(model=_CHAIRMAN, messages=[{"role": "system", "content": hydration}, {"role": "user", "content": prompt}], timeout=120.0)
            if not text:
                raise ValueError("ollama_safe returned empty response")
            return text
        except Exception as e:
            logger.warning(f"[VECTOR][journal_writer] LLM unavailable: {e}")
            return f"*{len(events)} events logged. Narrative synthesis unavailable.*"

    async def write_daily(self) -> bool:
        date_str = datetime.date.today().isoformat()
        events = self._fetch_events(hours=24)
        if not events:
            events = [{"event_type": "idle", "content": "Quiet day.", "timestamp": date_str, "tags": "", "source": "system"}]

        hydration = self._context.session_hydration_prompt()
        narrative = self._narrative(events, hydration, "daily")

        try:
            self._obsidian.write_note(
                title=f"Journal — {date_str}",
                content=(
                    f"# Journal — {date_str}\n\n{narrative}\n\n"
                    f"---\n*{len(events)} events · auto-generated by JournalWriter*"
                ),
                folder="Journals",
                tags=["journal", "daily", "vector"],
            )
            self._memory.store(
                event_type="journal_written",
                content=f"Daily journal: {date_str}, {len(events)} events",
                tags=["journal", "daily"],
                source="journal_writer",
            )
            self._memory.store_chain(
                situation="daily_journal",
                goal_ids=["self_improvement"],
                steps=["fetch_events", "llm_narrative", "obsidian_write"],
                action="write_daily",
                outcome=f"{len(events)} events → journal written",
                reward=0.8,
            )
            self.award_points(40, f"daily journal {date_str}")
            logger.info(f"[VECTOR][journal_writer] daily journal written: {date_str}")
            return True
        except Exception as e:
            logger.error(f"[VECTOR][journal_writer] write failed: {e}")
            self.deduct_points(10, "journal write failed")
            return False

    async def write_weekly(self) -> bool:
        events = self._fetch_events(hours=168)
        week_label = datetime.date.today().strftime("W%V-%Y")

        if not events:
            events = [{"event_type": "idle", "content": "Quiet week.", "timestamp": datetime.date.today().isoformat(), "tags": "", "source": "system"}]

        hydration = self._context.session_hydration_prompt()
        narrative = self._narrative(events, hydration, "weekly review")

        try:
            self._obsidian.write_note(
                title=f"Weekly Review — {week_label}",
                content=(
                    f"# Weekly Review — {week_label}\n\n{narrative}\n\n"
                    f"---\n*{len(events)} events · auto-generated by JournalWriter*"
                ),
                folder="Reviews",
                tags=["review", "weekly", "vector"],
            )
            self._memory.store(
                event_type="weekly_review_written",
                content=f"Weekly review: {week_label}, {len(events)} events",
                tags=["journal", "weekly"],
                source="journal_writer",
            )
            self._memory.store_chain(
                situation="weekly_journal",
                goal_ids=["self_improvement"],
                steps=["fetch_events", "llm_narrative", "obsidian_write"],
                action="write_weekly",
                outcome=f"{len(events)} events → weekly review written",
                reward=0.85,
            )
            self.award_points(60, f"weekly review {week_label}")
            logger.info(f"[VECTOR][journal_writer] weekly review written: {week_label}")
            return True
        except Exception as e:
            logger.error(f"[VECTOR][journal_writer] weekly write failed: {e}")
            self.deduct_points(10, "weekly write failed")
            return False

    async def run(self, task: dict) -> dict:
        t = task.get("type", "")
        if t == "weekly_journal":
            ok = await self.write_weekly()
        else:
            ok = await self.write_daily()
        return {"status": "ok" if ok else "error"}

    async def run_forever(self) -> None:
        logger.info("[VECTOR][journal_writer] run_forever — daily 22:30, weekly Sunday 23:00")
        while self.is_alive:
            try:
                now = datetime.datetime.now()
                if now.hour == 22 and 30 <= now.minute < 35:
                    await self.write_daily()
                if now.weekday() == 6 and now.hour == 23 and 0 <= now.minute < 5:
                    await self.write_weekly()
            except Exception as e:
                logger.error(f"[VECTOR][journal_writer] tick: {e}")
                self.deduct_points(5, "tick error")
            for _ in range(300):
                if not self.is_alive:
                    break
                await asyncio.sleep(60)
        logger.warning("[VECTOR][journal_writer] died — HP=0")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    import tempfile

    async def _smoke():
        bot = JournalWriter()
        assert bot.health_points == 500
        with tempfile.TemporaryDirectory() as d:
            vault = Path(d)
            (vault / "Journals").mkdir()
            (vault / "Reviews").mkdir()
            bot._obsidian._vault = vault
            ok = await bot.write_daily()
        print(f"OK journal_writer.py HP={bot.health_points} ok={ok}")

    asyncio.run(_smoke())
