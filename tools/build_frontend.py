"""Build the production VECTOR HUD bundle.

This intentionally avoids external JS tooling: the HUD modules are classic
browser scripts that attach to window, so preserving the existing production
HTML order is enough for a deterministic bundle.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from datetime import datetime, timezone
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT / "frontend"
PROD_HTML = FRONTEND / "VECTOR.prod.html"
DIST = FRONTEND / "dist"
BUNDLE = DIST / "vector-hud.prod.js"
MANIFEST = DIST / "manifest.json"
RUNTIME_SCRIPTS = {"js/config.js"}
PROD_SCRIPT_ORDER = [
    "js/data.js",
    "js/orb.js",
    "js/ambient.js",
    "js/vector-core.js",
    "js/audio.js",
    "js/voice_duplex.js",
    "js/approvals.js",
    "js/ventures.js",
    "js/widgets.js",
    "js/gestures.js",
    "js/face.js",
    "js/speech.js",
    "js/cinematic.js",
    "js/terminal.js",
    "js/command-box.js",
    "js/provider-keys.js",
    "js/hud-controls.js",
    "js/city3d.js",
    "js/backend.js",
    "js/offline.js",
]


def extract_scripts(html: str) -> list[str]:
    return [
        src.replace("\\", "/")
        for src in re.findall(r"<script\b[^>]*\bsrc=[\"']([^\"']+)[\"']", html, flags=re.I)
        if not re.match(r"^[a-z][a-z0-9+.-]*:", src, flags=re.I) and not src.startswith("//")
    ]


def build_bundle(*, write: bool = True) -> dict[str, object]:
    html = PROD_HTML.read_text(encoding="utf-8")
    scripts = extract_scripts(html)
    if "dist/vector-hud.prod.js" in scripts:
        bundled = PROD_SCRIPT_ORDER[:]
    else:
        bundled = [src for src in scripts if src not in RUNTIME_SCRIPTS and not src.startswith("dist/")]
    missing = [src for src in bundled if not (FRONTEND / src).is_file()]
    if missing:
        raise FileNotFoundError("Missing frontend scripts: " + ", ".join(missing))

    chunks = [
        "/* VECTOR production HUD bundle. Generated by tools/build_frontend.py. */",
        "/* Do not edit this file directly; edit frontend/js/*.js and rebuild. */",
        "",
    ]
    for src in bundled:
        text = (FRONTEND / src).read_text(encoding="utf-8")
        chunks.append(f"\n/* ---- {src} ---- */\n")
        chunks.append(text.rstrip() + "\n")

    bundle_text = "\n".join(chunks)
    digest = hashlib.sha256(bundle_text.encode("utf-8")).hexdigest()
    manifest = {
        "entry": "dist/vector-hud.prod.js",
        "runtime_scripts": sorted(RUNTIME_SCRIPTS),
        "bundled_scripts": bundled,
        "sha256": digest,
        "bytes": len(bundle_text.encode("utf-8")),
        "built_at": datetime.now(timezone.utc).isoformat(),
    }

    if write:
        DIST.mkdir(parents=True, exist_ok=True)
        BUNDLE.write_text(bundle_text, encoding="utf-8")
        MANIFEST.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description="Build VECTOR production HUD bundle")
    parser.add_argument("--check", action="store_true", help="verify generated files are current")
    args = parser.parse_args()

    if args.check:
        expected = build_bundle(write=False)
        current_bundle = BUNDLE.read_text(encoding="utf-8") if BUNDLE.exists() else ""
        current_hash = hashlib.sha256(current_bundle.encode("utf-8")).hexdigest() if current_bundle else ""
        if current_hash != expected["sha256"]:
            raise SystemExit("frontend bundle is stale; run: python tools/build_frontend.py")
        current_manifest = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.exists() else {}
        if current_manifest.get("bundled_scripts") != expected["bundled_scripts"]:
            raise SystemExit("frontend manifest script order is stale; run: python tools/build_frontend.py")
        print("frontend bundle is current")
        return 0

    manifest = build_bundle(write=True)
    print(f"built {manifest['entry']} ({manifest['bytes']} bytes, sha256={manifest['sha256'][:12]})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
