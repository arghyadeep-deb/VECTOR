"""
VECTOR Gap 5 — SuggestionQueue.
SQLite-backed queue that persists hypotheses generated by HypothesisEngine.
_reflect_tick drains top-3 by confidence every cycle.
"""
from __future__ import annotations

from core.memory.db_utils import apply_pragmas
__all__ = ["SuggestionQueue"]

import sqlite3
import threading
import uuid
from datetime import datetime, timezone
from pathlib import Path


from loguru import logger
from core.config import CONFIG

from core.runtime_paths import data_path

_DEFAULT_DB = data_path("suggestion_queue.db")


class SuggestionQueue:
    """Persistent queue for proactive hypotheses awaiting user surfacing."""

    def __init__(self, db_path: str | Path | None = None):
        self._db_path = Path(db_path) if db_path else _DEFAULT_DB
        self._db_path.parent.mkdir(parents=True, exist_ok=True)
        self._conn = sqlite3.connect(str(self._db_path), check_same_thread=False)
        self._conn.row_factory = sqlite3.Row
        apply_pragmas(self._conn)
        self._lock = threading.RLock()
        self._conn.execute("""
            CREATE TABLE IF NOT EXISTS suggestion_queue (
                id          TEXT PRIMARY KEY,
                hypothesis  TEXT NOT NULL,
                confidence  REAL NOT NULL DEFAULT 0.7,
                status      TEXT NOT NULL DEFAULT 'pending',
                created_at  TEXT NOT NULL,
                surfaced_at TEXT
            )
        """)
        self._conn.commit()
        logger.debug("[VECTOR][suggestion_queue] initialized at {}", self._db_path)

    def enqueue(self, hypothesis: str, confidence: float = 0.7) -> str:
        """Add a hypothesis with status='pending'. Returns the new id."""
        hid = uuid.uuid4().hex[:12]
        now = datetime.now(timezone.utc).isoformat()
        self._conn.execute(
            "INSERT INTO suggestion_queue (id, hypothesis, confidence, status, created_at) VALUES (?,?,?,?,?)",
            (hid, hypothesis[:500], float(confidence), "pending", now),
        )
        self._conn.commit()
        logger.debug("[VECTOR][suggestion_queue] enqueued id={} conf={:.2f}", hid, confidence)
        return hid

    def get_top_pending(self, limit: int = 3) -> list[dict]:
        """Return top-N pending hypotheses ordered by confidence DESC."""
        rows = self._conn.execute(
            "SELECT * FROM suggestion_queue WHERE status='pending' ORDER BY confidence DESC LIMIT ?",
            (limit,),
        ).fetchall()
        return [dict(r) for r in rows]

    def mark_surfaced(self, hid: str) -> None:
        """Mark a hypothesis as surfaced (status='surfaced', set surfaced_at)."""
        now = datetime.now(timezone.utc).isoformat()
        self._conn.execute(
            "UPDATE suggestion_queue SET status='surfaced', surfaced_at=? WHERE id=?",
            (now, hid),
        )
        self._conn.commit()

    def get_all(self, limit: int = 50) -> list[dict]:
        """Return all rows ordered by created_at DESC."""
        rows = self._conn.execute(
            "SELECT * FROM suggestion_queue ORDER BY created_at DESC LIMIT ?",
            (limit,),
        ).fetchall()
        return [dict(r) for r in rows]

    def count_pending(self) -> int:
        row = self._conn.execute("SELECT COUNT(*) FROM suggestion_queue WHERE status='pending'").fetchone()
        return row[0] if row else 0

    def close(self) -> None:
        try:
            self._conn.close()
        except Exception as e:
            logger.warning("[VECTOR] silent swallow: %s", e)
            pass


if __name__ == "__main__":
    sq = SuggestionQueue(db_path=":memory:")
    hid = sq.enqueue("Users are most productive between 9-11am", confidence=0.82)
    sq.enqueue("Commit frequency correlates with sleep quality", confidence=0.75)
    sq.enqueue("Python imports slow down at 6pm", confidence=0.61)
    pending = sq.get_top_pending(3)
    print(f"Top pending ({len(pending)}):", [p["hypothesis"][:40] for p in pending])
    sq.mark_surfaced(pending[0]["id"])
    print("After surfacing:", sq.count_pending(), "pending")
    sq.close()
