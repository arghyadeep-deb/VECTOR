"""Non-destructive source/runtime hygiene checks for the VECTOR repository."""

from __future__ import annotations

from dataclasses import dataclass
from fnmatch import fnmatch
from pathlib import Path


@dataclass(frozen=True)
class HygieneFinding:
    path: str
    category: str
    severity: str
    reason: str


RUNTIME_PATTERNS: tuple[tuple[str, str], ...] = (
    (".coverage", "coverage database generated by test runs"),
    (".pytest_cache/**", "pytest cache generated by test runs"),
    ("test_tmp/**", "temporary pytest/runtime output"),
    ("logs/**", "runtime log output"),
    ("*.log", "runtime log output"),
    ("**/__pycache__/**", "Python bytecode cache"),
    ("**/*.pyc", "Python bytecode cache"),
    ("data/feedback/action_*.json", "feedback event generated at runtime"),
    ("data/rejected_runs/*.json", "rejected run generated at runtime"),
    ("data/reports/cycle_*.md", "generated training/report artifact"),
    ("data/security/incidents/**", "security incident evidence generated at runtime"),
    ("data/missions/**", "mission history generated at runtime"),
    ("data/runtime/**", "runtime state generated by VECTOR"),
    ("data/verification/**", "production verification output"),
    ("frontend/screenshots/**", "frontend screenshot artifact"),
    ("frontend/uploads/**", "local uploaded media artifact"),
    ("districts/investment/vector_backtest/sessions/**", "backtest session output"),
)

SENSITIVE_PATTERNS: tuple[tuple[str, str], ...] = (
    (".env", "environment secrets file"),
    (".env.*", "environment secrets file"),
    ("*.pem", "private key or certificate material"),
    ("*.p12", "private key store"),
    ("*.pfx", "private key store"),
    ("*.key", "private key material"),
    ("certs/*.key", "TLS private key material"),
    ("**/wormhole_secure_store.key", "encrypted store key material"),
)


ALLOWED_ENV_TEMPLATES = {
    ".env.example",
    ".env.hardened.example",
    ".env.local.example",
}


def normalize_repo_path(path: str | Path) -> str:
    """Normalize a path to a repo-relative POSIX-style string."""
    return str(path).replace("\\", "/").strip("/")


def _matches(path: str, pattern: str) -> bool:
    return fnmatch(path, pattern) or fnmatch("/" + path, pattern)


def classify_repo_path(path: str | Path) -> HygieneFinding | None:
    normalized = normalize_repo_path(path)

    if normalized in ALLOWED_ENV_TEMPLATES:
        return None

    for pattern, reason in SENSITIVE_PATTERNS:
        if _matches(normalized, pattern):
            return HygieneFinding(
                path=normalized,
                category="sensitive",
                severity="high",
                reason=reason,
            )

    for pattern, reason in RUNTIME_PATTERNS:
        if _matches(normalized, pattern):
            return HygieneFinding(
                path=normalized,
                category="runtime",
                severity="medium",
                reason=reason,
            )

    return None


def audit_repo_paths(paths: list[str | Path]) -> list[HygieneFinding]:
    findings = [finding for path in paths if (finding := classify_repo_path(path))]
    return sorted(findings, key=lambda item: (item.severity, item.category, item.path))
