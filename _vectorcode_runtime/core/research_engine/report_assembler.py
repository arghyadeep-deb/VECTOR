"""Report assembler — builds ResearchReport from hypothesis, experiment, and analysis."""

from datetime import datetime, timezone

__all__ = [
    "OBSIDIAN_VAULT",
    "ReportAssembler",
    "TEMPLATES_DIR",
]

from pathlib import Path
from typing import Optional

from loguru import logger

from .models import Hypothesis, ExperimentDesign, ExperimentResult, AnalysisResult, ResearchReport

TEMPLATES_DIR = Path(__file__).parent / "templates"
OBSIDIAN_VAULT = Path.home() / "VECTOR" / "Obsidian" / "Research Reports"


class ReportAssembler:
    def __init__(self, vault_path: Optional[Path] = None):
        self.vault_path = vault_path or OBSIDIAN_VAULT
        self._jinja_env: Optional[object] = None

    def _load_jinja(self) -> Optional[object]:
        if self._jinja_env is not None:
            return self._jinja_env
        try:
            from jinja2 import Environment, FileSystemLoader

            loader = FileSystemLoader(str(TEMPLATES_DIR))
            self._jinja_env = Environment(loader=loader)
        except ImportError:
            logger.warning("jinja2 not available — using plain text formatting")
            self._jinja_env = None
        return self._jinja_env

    def assemble(
        self,
        hypothesis: Optional[Hypothesis] = None,
        experiment: Optional[ExperimentDesign] = None,
        analysis: Optional[AnalysisResult] = None,
    ) -> ResearchReport:
        sections = {
            "title": f"Research Report: {hypothesis.title if hypothesis else 'Untitled'}",
            "hypothesis": self._format_section("Hypothesis", hypothesis),
            "methodology": self._format_section("Methodology", experiment),
            "results": self._format_section("Results", analysis),
            "analysis": self._format_section("Analysis", analysis, detail=True),
            "conclusion": self._build_conclusion(hypothesis, analysis),
        }
        references = self._generate_references(hypothesis)

        figures: list[str] = []
        if analysis and analysis.experiment_id:
            pass

        report = ResearchReport(
            hypothesis=hypothesis,
            experiment=experiment,
            analysis=analysis,
            sections=sections,
            figures=figures,
            references=references,
            generated_at=datetime.now(timezone.utc).isoformat(),
        )

        self._save_to_vault(report)
        return report

    def _format_section(self, name: str, obj: object, detail: bool = False) -> str:
        if obj is None:
            return f"## {name}\n\nNo data available.\n"

        lines = [f"## {name}\n"]
        if hasattr(obj, "__dataclass_fields__"):
            for field_name, field_value in obj.__dataclass_fields__.items():
                if field_name.startswith("_"):
                    continue
                val = getattr(obj, field_name, None)
                if val is None or val == "" or val == {} or val == []:
                    continue
                if isinstance(val, list) and not detail:
                    lines.append(f"- **{field_name.replace('_', ' ').title()}**: {len(val)} entries")
                elif isinstance(val, dict) and not detail:
                    lines.append(f"- **{field_name.replace('_', ' ').title()}**: {len(val)} keys")
                else:
                    display = str(val)
                    if len(display) > 200:
                        display = display[:200] + "..."
                    lines.append(f"- **{field_name.replace('_', ' ').title()}**: {display}")
        lines.append("")
        return "\n".join(lines)

    def _build_conclusion(
        self,
        hypothesis: Optional[Hypothesis],
        analysis: Optional[AnalysisResult],
    ) -> str:
        lines = ["## Conclusion\n"]
        if analysis and analysis.supports_hypothesis:
            lines.append("The experimental evidence supports the hypothesis.")
        elif analysis:
            lines.append("The experimental evidence does not support the hypothesis.")
        else:
            lines.append("Analysis incomplete — conclusion cannot be drawn.")

        if analysis:
            lines.append(f"\n**Interpretation**: {analysis.interpretation}")
            lines.append(f"\n**Significance**: p = {analysis.significance:.4f}")
            lines.append(f"\n**Effect Size**: {analysis.effect_size:.4f}")
        lines.append("")
        return "\n".join(lines)

    def _generate_references(self, hypothesis: Optional[Hypothesis]) -> list[str]:
        refs: list[str] = []
        if hypothesis and hypothesis.source:
            refs.append(f"Hypothesis source: {hypothesis.source}")
        refs.append(f"Generated by VECTOR Research Engine ({datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')})")
        return refs

    def render_markdown(self, report: ResearchReport) -> str:
        env = self._load_jinja()
        if env is not None:
            try:
                tmpl = env.get_template("report.md.j2")
                return tmpl.render(
                    report=report,
                    hypothesis=report.hypothesis,
                    experiment=report.experiment,
                    analysis=report.analysis,
                )
            except Exception as exc:
                logger.warning("Jinja2 render failed, falling back: {}", exc)

        parts = [
            f"# {report.sections.get('title', 'Research Report')}",
            "",
            report.sections.get("hypothesis", ""),
            report.sections.get("methodology", ""),
            report.sections.get("results", ""),
            report.sections.get("analysis", ""),
            report.sections.get("conclusion", ""),
        ]
        if report.references:
            parts.append("## References\n")
            for ref in report.references:
                parts.append(f"- {ref}")
            parts.append("")
        return "\n\n".join(parts)

    def _save_to_vault(self, report: ResearchReport) -> None:
        vault = self.vault_path
        if not vault:
            return
        try:
            vault.mkdir(parents=True, exist_ok=True)
            slug = "report"
            if report.hypothesis:
                slug = report.hypothesis.title.lower().replace(" ", "_").replace("/", "_")[:60]
            fname = vault / f"{slug}_{datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')}.md"
            content = self.render_markdown(report)
            fname.write_text(content, encoding="utf-8")
            logger.info("Saved report to Obsidian vault: {}", fname)
        except Exception as exc:
            logger.warning("Failed to save report to vault: {}", exc)
