import sys
import uuid
import asyncio
import datetime
from pathlib import Path

from core.config import CONFIG
from core.city.agent_base import AgentBase
from core.memory.episodic import EpisodicMemory
from core.memory.obsidian_sync import ObsidianSync
from core.loop.context_engine import ContextEngine
from loguru import logger

_CHAIRMAN = CONFIG["models"]["chairman"]


class JournalWriter(AgentBase):
    """
    Writes daily/weekly Obsidian journal entries from episodic events.
    Daily at 22:30, weekly review on Sunday 23:00.
    RULE 11: vector-reasoning (local), not Claude API.
    """

    def __init__(self, generation: int = 1, ghost: dict | None = None):
        super().__init__(
            agent_id=str(uuid.uuid4()),
            name="JournalWriter",
            district="reflection",
            generation=generation,
        )
        self.capabilities = ["daily_journal", "daily_review", "journal", "reflect", "weekly_journal"]
        if ghost:
            self.inherit_ghost(ghost)
        self._memory = EpisodicMemory()
        self._obsidian = ObsidianSync()
        self._context = ContextEngine()
        logger.info(f"[VECTOR][journal_writer] ready gen={generation}")

    def _fetch_events(self, hours: int = 24) -> list[dict] | None:
        """Events in the last `hours`. None = the DB read FAILED (distinct from [] = no activity)."""
        # episodic_memory.timestamp is aware UTC ISO text; a naive local cutoff shifted the window.
        cutoff = (datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(hours=hours)).isoformat()
        try:
            cur = self._memory.conn.cursor()
            cur.execute(
                "SELECT event_type, content, tags, source, timestamp FROM episodic_memory "
                "WHERE timestamp > ? AND COALESCE(source, '') NOT LIKE '%test%' "
                "AND COALESCE(tags, '') NOT LIKE '%\"test\"%' ORDER BY timestamp ASC",
                (cutoff,),
            )
            cols = [d[0] for d in cur.description]
            return [dict(zip(cols, r)) for r in cur.fetchall()]
        except Exception as e:
            logger.warning("[VECTOR][journal_writer] fetch failed: {}", e)
            return None

    def _narrative(self, events: list[dict], hydration: str, entry_type: str) -> str | None:
        """LLM narrative, or None when no model produced one (never a canned placeholder)."""
        summary = "\n".join(
            f"[{e.get('timestamp','')[:16]}] {e.get('event_type','')}: {e.get('content','')[:100]}"
            for e in events[:80]
        )
        prompt = (
            f"You are writing a personal journal entry ({entry_type}) for Arghyadeep based on his activity.\n\n"
            f"Activity log ({len(events)} events):\n{summary}\n\n"
            "Write a reflective, personal journal entry in first person. Structure:\n"
            "**What happened** - key events and accomplishments\n"
            "**How I felt / what I noticed** - patterns, energy, focus\n"
            "**What I learned** - insights, realisations\n"
            "**Tomorrow's intention** - one clear focus\n\n"
            "Be concise, genuine, and specific."
        )
        try:
            from core.inference.vectorcode_llm import chat
            text = chat(model=_CHAIRMAN, messages=[{"role": "system", "content": hydration}, {"role": "user", "content": prompt}], timeout=120.0)
            if not text:
                raise ValueError("ollama_safe returned empty response")
            return text
        except Exception as e:
            logger.warning("[VECTOR][journal_writer] LLM unavailable: {}", e)
            return None

    async def write_daily(self) -> bool:
        date_str = datetime.date.today().isoformat()
        events = self._fetch_events(hours=24)
        if events is None:
            logger.error("[VECTOR][journal_writer] daily journal aborted: event fetch failed")
            return False
        if events:
            narrative = self._narrative(events, self._context.session_hydration_prompt(), "daily")
            if narrative is None:
                logger.error("[VECTOR][journal_writer] daily journal aborted: no LLM narrative available")
                return False
        else:
            # Nothing logged: state that; don't have the LLM invent a first-person day.
            narrative = "*No activity was logged in the last 24 hours.*"

        try:
            self._obsidian.write_note(
                title=f"Journal — {date_str}",
                content=(
                    f"# Journal — {date_str}\n\n{narrative}\n\n"
                    f"---\n*{len(events)} events · auto-generated by JournalWriter*"
                ),
                folder="Journals",
                tags=["journal", "daily", "vector"],
            )
            self._memory.store(
                event_type="journal_written",
                content=f"Daily journal: {date_str}, {len(events)} events",
                tags=["journal", "daily"],
                source="journal_writer",
            )
            self._memory.store_chain(
                situation="daily_journal",
                goal_ids=["self_improvement"],
                steps=["fetch_events", "llm_narrative", "obsidian_write"],
                action="write_daily",
                outcome=f"{len(events)} events → journal written",
                reward=0.8,
            )
            self.award_points(40, f"daily journal {date_str}")
            logger.info(f"[VECTOR][journal_writer] daily journal written: {date_str}")
            return True
        except Exception as e:
            logger.error(f"[VECTOR][journal_writer] write failed: {e}")
            self.deduct_points(10, "journal write failed")
            return False

    async def write_weekly(self) -> bool:
        events = self._fetch_events(hours=168)
        # %G (ISO year) with %V (ISO week): %Y mislabels e.g. 2025-12-29 as W01-2025 and would
        # overwrite the real W01-2025 note.
        week_label = datetime.date.today().strftime("W%V-%G")

        if events is None:
            logger.error("[VECTOR][journal_writer] weekly review aborted: event fetch failed")
            return False
        if events:
            narrative = self._narrative(events, self._context.session_hydration_prompt(), "weekly review")
            if narrative is None:
                logger.error("[VECTOR][journal_writer] weekly review aborted: no LLM narrative available")
                return False
        else:
            narrative = "*No activity was logged in the last 7 days.*"

        try:
            self._obsidian.write_note(
                title=f"Weekly Review — {week_label}",
                content=(
                    f"# Weekly Review — {week_label}\n\n{narrative}\n\n"
                    f"---\n*{len(events)} events · auto-generated by JournalWriter*"
                ),
                folder="Reviews",
                tags=["review", "weekly", "vector"],
            )
            self._memory.store(
                event_type="weekly_review_written",
                content=f"Weekly review: {week_label}, {len(events)} events",
                tags=["journal", "weekly"],
                source="journal_writer",
            )
            self._memory.store_chain(
                situation="weekly_journal",
                goal_ids=["self_improvement"],
                steps=["fetch_events", "llm_narrative", "obsidian_write"],
                action="write_weekly",
                outcome=f"{len(events)} events → weekly review written",
                reward=0.85,
            )
            self.award_points(60, f"weekly review {week_label}")
            logger.info(f"[VECTOR][journal_writer] weekly review written: {week_label}")
            return True
        except Exception as e:
            logger.error(f"[VECTOR][journal_writer] weekly write failed: {e}")
            self.deduct_points(10, "weekly write failed")
            return False

    async def answer_reflection_question(self, query: str) -> str:
        """Answer a free-text question routed to JournalWriter instead of
        blindly writing a new Obsidian journal note on every call
        regardless of what was actually asked (KNOWN_ISSUES bug pattern: a
        real, unrelated file-write side effect from a stray conversational
        message). Grounded in today's real event log."""
        events = self._fetch_events(hours=24)
        if events is None:
            return ""  # DB read failed: don't tell the LLM "no activity" and let it answer from nothing
        summary = "\n".join(
            f"[{e.get('timestamp','')[:16]}] {e.get('event_type','')}: {e.get('content','')[:120]}"
            for e in events[:30]
        ) or "No activity logged today."
        prompt = (
            "You are VECTOR's JournalWriter in the reflection district. "
            "Answer the owner's question using today's real activity log "
            f"below — do not invent data you don't have:\n\n{summary}\n\n"
            f"Question: {query}"
        )
        try:
            from core.inference.vectorcode_llm import chat
            hydration = self._context.session_hydration_prompt()
            text = chat(model=_CHAIRMAN, messages=[{"role": "system", "content": hydration}, {"role": "user", "content": prompt}], timeout=60.0)
            return (text or "").strip()
        except Exception as e:
            logger.warning(f"[VECTOR][journal_writer] answer_reflection_question failed: {e}")
            return ""

    async def run(self, task: dict) -> dict:
        # 2026-08-06: run() used to fall through to write_daily() for
        # ANY unmatched task_type with no query text — a stray
        # conversational message would write a full Obsidian journal
        # entry. Now gated behind explicit task_type; unmatched types
        # with no query return a grounded status instead.
        t = task.get("type", "")
        query = (
            (task.get("params") or {}).get("query")
            or task.get("query")
            or task.get("text")
            or ""
        ).strip()
        if query and t not in ("weekly_journal", "daily_journal"):
            answer = await self.answer_reflection_question(query)
            if answer:
                self.award_points(10, "reflection_question_answered")
                return {"status": "ok", "response": answer}

        if t == "weekly_journal":
            ok = await self.write_weekly()
            return {"status": "ok" if ok else "error"}
        elif t == "daily_journal":
            ok = await self.write_daily()
            return {"status": "ok" if ok else "error"}

        # No query and no explicit journal request — return status, no side effects
        return {"status": "ok", "response": "JournalWriter ready. Use task_type='daily_journal' or 'weekly_journal', or ask a question."}

    async def run_forever(self) -> None:
        logger.info("[VECTOR][journal_writer] run_forever — daily 22:30, weekly Sunday 23:00")
        while self.is_alive:
            try:
                now = datetime.datetime.now()
                if now.hour == 22 and 30 <= now.minute < 35:
                    await self.write_daily()
                if now.weekday() == 6 and now.hour == 23 and 0 <= now.minute < 5:
                    await self.write_weekly()
            except Exception as e:
                logger.error(f"[VECTOR][journal_writer] tick: {e}")
                self.deduct_points(5, "tick error")
            for _ in range(300):
                if not self.is_alive:
                    break
                await asyncio.sleep(60)
        logger.warning("[VECTOR][journal_writer] died — HP=0")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    import tempfile

    async def _smoke():
        bot = JournalWriter()
        assert bot.health_points == 500
        with tempfile.TemporaryDirectory() as d:
            vault = Path(d)
            (vault / "Journals").mkdir()
            (vault / "Reviews").mkdir()
            bot._obsidian._vault = vault
            ok = await bot.write_daily()
        print(f"OK journal_writer.py HP={bot.health_points} ok={ok}")

    asyncio.run(_smoke())
