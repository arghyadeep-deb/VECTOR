# Indian tax calendar deadlines (month, day, label)
_TAX_DEADLINES: list[tuple[int, int, str]] = [
    (3, 31, "FY end — finalise income/investments"),
    (4, 1, "New FY begins — update tax regime choice"),
    (6, 15, "Advance tax — 15% Q1 payment"),
    (7, 31, "ITR filing deadline (non-audit)"),
    (9, 15, "Advance tax — 45% cumulative Q2"),
    (10, 31, "ITR filing deadline (audit cases)"),
    (12, 15, "Advance tax — 75% cumulative Q3"),
    (3, 15, "Advance tax — 100% cumulative Q4"),
    (1, 31, "Form 16 / TDS certificate collection"),
    (2, 1, "Union Budget — review tax rule changes"),
    (2, 15, "15G/15H submission if applicable"),
]


class TaxCalendar(AgentBase):
    """
    Tracks Indian tax deadlines. Notifies 7 days and 1 day before each deadline.
    Writes upcoming deadlines to Obsidian. ANALYSIS ONLY — never files or pays.
    """

    def __init__(self, generation: int = 1, ghost: dict | None = None):
        super().__init__(
            agent_id=str(uuid.uuid4()),
            name="TaxCalendar",
            district="finance",
            generation=generation,
        )
        self.capabilities = ["deadline", "finance", "tax"]
        if ghost:
            self.inherit_ghost(ghost)
        self._memory = EpisodicMemory()
        self._obsidian = ObsidianSync()
        logger.info(f"[VECTOR][tax_calendar] ready gen={generation}")

    def upcoming_deadlines(self, within_days: int = 30) -> list[dict]:
        today = datetime.date.today()
        year = today.year
        upcoming = []

        for month, day, label in _TAX_DEADLINES:
            try:
                deadline = datetime.date(year, month, day)
                if deadline < today:
                    # Try next year
                    deadline = datetime.date(year + 1, month, day)
                delta = (deadline - today).days
                if 0 <= delta <= within_days:
                    upcoming.append({
                        "date": deadline.isoformat(),
                        "days_away": delta,
                        "label": label,
                        "urgency": "critical" if delta <= 1 else "high" if delta <= 7 else "medium",
                    })
            except ValueError:
                continue

        return sorted(upcoming, key=lambda x: x["days_away"])

    async def check_and_notify(self) -> bool:
        today = datetime.date.today().isoformat()
        due_7 = self.upcoming_deadlines(within_days=7)
        due_1 = [d for d in due_7 if d["days_away"] <= 1]

        if not due_7:
            logger.info("[VECTOR][tax_calendar] no deadlines in next 7 days")
            return True

        for item in due_1:
            self._memory.store(
                event_type="tax_alert",
                content=f"TAX DEADLINE TODAY/TOMORROW: {item['label']} ({item['date']})",
                tags=["finance", "tax", "critical"],
                source="tax_calendar",
            )
            logger.warning(f"[VECTOR][tax_calendar] CRITICAL: {item['label']} due {item['date']}")

        for item in due_7:
            if item["days_away"] > 1:
                self._memory.store(
                    event_type="tax_reminder",
                    content=f"Tax deadline in {item['days_away']} days: {item['label']} ({item['date']})",
                    tags=["finance", "tax", "reminder"],
                    source="tax_calendar",
                )
                logger.info(f"[VECTOR][tax_calendar] reminder: {item['label']} in {item['days_away']} days")

        self.award_points(10, "tax calendar checked")
        return True

    async def write_calendar_note(self) -> bool:
        year = datetime.date.today().year
        all_deadlines = []
        for month, day, label in _TAX_DEADLINES:
            try:
                d = datetime.date(year, month, day)
                all_deadlines.append({"date": d.isoformat(), "label": label})
            except ValueError:
                continue
        all_deadlines.sort(key=lambda x: x["date"])

        rows = "\n".join(f"| {d['date']} | {d['label']} |" for d in all_deadlines)
        content = (
            f"# Tax Calendar — FY {year}-{year+1}\n\n"
            f"**ANALYSIS ONLY — VECTOR never files or pays automatically.**\n\n"
            f"| Date | Deadline |\n|------|----------|\n{rows}\n\n"
            f"---\n*auto-generated by TaxCalendar · verify with CA before acting*"
        )

        try:
            self._obsidian.write_note(
                title=f"Tax Calendar — {year}",
                content=content,
                folder="Finance",
                tags=["finance", "tax", "calendar", "vector"],
            )
            self._memory.store(
                event_type="tax_calendar_written",
                content=f"Tax calendar written: {year}, {len(all_deadlines)} deadlines",
                tags=["finance", "tax"],
                source="tax_calendar",
            )
            self.award_points(20, f"tax calendar {year}")
            logger.info(f"[VECTOR][tax_calendar] calendar note written: {year}")
            return True
        except Exception as e:
            logger.error(f"[VECTOR][tax_calendar] write failed: {e}")
            self.deduct_points(5, "write failed")
            return False

    async def run(self, task: dict) -> dict:
        deadlines = self.upcoming_deadlines()
        return {"status": "ok", "deadlines": deadlines, "count": len(deadlines)}

    async def run_forever(self) -> None:
        logger.info("[VECTOR][tax_calendar] run_forever — daily check at 09:00")
        while self.is_alive:
            try:
                now = datetime.datetime.now()
                if now.hour == 9 and 0 <= now.minute < 5:
                    await self.check_and_notify()
                # Rewrite calendar note on April 1 (new FY)
                if now.month == 4 and now.day == 1 and now.hour == 0 and now.minute < 5:
                    await self.write_calendar_note()
            except Exception as e:
                logger.error(f"[VECTOR][tax_calendar] tick: {e}")
                self.deduct_points(5, "tick error")
            for _ in range(300):
                if not self.is_alive:
                    break
                await asyncio.sleep(60)
        logger.warning("[VECTOR][tax_calendar] died — HP=0")


