import sys
import uuid
import asyncio
import datetime
from pathlib import Path

from core.config import CONFIG
from core.city.agent_base import AgentBase
from core.memory.episodic import EpisodicMemory
from core.memory.obsidian_sync import ObsidianSync
from core.loop.context_engine import ContextEngine
from loguru import logger


class ExpenseTracker(AgentBase):
    """
    Aggregates UPI transactions into daily/weekly/monthly expense summaries.
    Writes categorised breakdowns to Obsidian.
    """

    def __init__(self, generation: int = 1, ghost: dict | None = None):
        super().__init__(
            agent_id=str(uuid.uuid4()),
            name="ExpenseTracker",
            district="finance",
            generation=generation,
        )
        self.capabilities = ["budget", "expense", "finance", "money", "monthly_report"]
        if ghost:
            self.inherit_ghost(ghost)
        self._memory = EpisodicMemory()
        self._obsidian = ObsidianSync()
        self._context = ContextEngine()
        logger.info(f"[VECTOR][expense_tracker] ready gen={generation}")

    def _fetch_transactions(self, days: int) -> list[dict]:
        cutoff = (datetime.datetime.now() - datetime.timedelta(days=days)).isoformat()
        try:
            cur = self._memory.conn.cursor()
            cur.execute(
                "SELECT content, tags, timestamp FROM episodic_memory "
                "WHERE event_type = 'upi_transaction' AND timestamp > ? ORDER BY timestamp DESC",
                (cutoff,),
            )
            cols = [d[0] for d in cur.description]
            return [dict(zip(cols, r)) for r in cur.fetchall()]
        except Exception as e:
            logger.warning(f"[VECTOR][expense_tracker] fetch failed: {e}")
            return []

    def _parse_amount(self, content: str) -> tuple[float, str, str]:
        """Extract (amount, direction, category) from stored content string."""
        import re
        direction = "debit" if "DEBIT" in content else "credit"
        m = re.search(r"Rs\.([\d.]+)", content)
        amount = float(m.group(1)) if m else 0.0
        # category is last word in brackets
        m2 = re.search(r"\[(\w+)\]", content)
        category = m2.group(1) if m2 else "other"
        return amount, direction, category

    def summarise(self, days: int = 30) -> dict:
        txns = self._fetch_transactions(days)
        by_category: dict[str, float] = {}
        total_debit = 0.0
        total_credit = 0.0

        for t in txns:
            amount, direction, category = self._parse_amount(t.get("content", ""))
            if direction == "debit":
                total_debit += amount
                by_category[category] = by_category.get(category, 0.0) + amount
            else:
                total_credit += amount

        return {
            "days": days,
            "total_debit": round(total_debit, 2),
            "total_credit": round(total_credit, 2),
            "net": round(total_credit - total_debit, 2),
            "by_category": {k: round(v, 2) for k, v in sorted(by_category.items(), key=lambda x: -x[1])},
            "transaction_count": len(txns),
        }

    async def write_monthly_report(self) -> bool:
        month_label = datetime.date.today().strftime("%Y-%m")
        summary = self.summarise(days=30)

        cat_lines = "\n".join(
            f"| {cat.capitalize()} | Rs.{amt:.2f} | {amt/summary['total_debit']*100:.1f}% |"
            for cat, amt in summary["by_category"].items()
        ) if summary["total_debit"] > 0 else "| No debit transactions |  |  |"

        report = (
            f"# Expense Report — {month_label}\n\n"
            f"**Total spent:** Rs.{summary['total_debit']:.2f}\n"
            f"**Total received:** Rs.{summary['total_credit']:.2f}\n"
            f"**Net:** Rs.{summary['net']:.2f}\n"
            f"**Transactions:** {summary['transaction_count']}\n\n"
            f"## Category Breakdown\n"
            f"| Category | Amount | Share |\n"
            f"|----------|--------|-------|\n"
            f"{cat_lines}\n\n"
            f"---\n*auto-generated by ExpenseTracker*"
        )

        try:
            self._obsidian.write_note(
                title=f"Expense Report — {month_label}",
                content=report,
                folder="Finance",
                tags=["finance", "expenses", "monthly", "vector"],
            )
            self._memory.store(
                event_type="expense_report",
                content=f"Monthly report {month_label}: spent Rs.{summary['total_debit']:.2f}",
                tags=["finance", "expenses"],
                source="expense_tracker",
            )
            self._memory.remember(
                key=f"monthly_spend:{month_label}",
                value=str(summary["total_debit"]),
                category="finance_monthly",
                confidence=0.95,
            )
            self.award_points(30, f"expense report {month_label}")
            logger.info(f"[VECTOR][expense_tracker] monthly report: Rs.{summary['total_debit']:.2f} spent")
            return True
        except Exception as e:
            logger.error(f"[VECTOR][expense_tracker] write failed: {e}")
            self.deduct_points(5, "write failed")
            return False

    async def run(self, task: dict) -> dict:
        p = task.get("params", {})
        t = task.get("type", "")
        if t in ("monthly_report", "finance_report"):
            ok = await self.write_monthly_report()
            return {"status": "ok" if ok else "error"}
        summary = self.summarise(p.get("days", 30))
        return {"status": "ok", **summary}

    async def run_forever(self) -> None:
        logger.info("[VECTOR][expense_tracker] run_forever — monthly report on 1st at 09:00")
        while self.is_alive:
            try:
                now = datetime.datetime.now()
                if now.day == 1 and now.hour == 9 and 0 <= now.minute < 5:
                    await self.write_monthly_report()
            except Exception as e:
                logger.error(f"[VECTOR][expense_tracker] tick: {e}")
                self.deduct_points(5, "tick error")
            for _ in range(300):
                if not self.is_alive:
                    break
                await asyncio.sleep(60)
        logger.warning("[VECTOR][expense_tracker] died — HP=0")


