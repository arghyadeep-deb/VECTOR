import sys
import uuid
import asyncio
import datetime
from pathlib import Path

from core.config import CONFIG
from core.city.agent_base import AgentBase
from core.memory.episodic import EpisodicMemory
from core.memory.obsidian_sync import ObsidianSync
from core.loop.context_engine import ContextEngine
from loguru import logger

from districts.projects._safe import safe_note_title

_REASONING = CONFIG["models"]["reasoning"]


class DocWriter(AgentBase):
    """
    Generates project documentation (README, architecture notes, API docs)
    from project context and code structure. Writes to Obsidian.
    RULE 11: vector-reasoning (local), not Claude API.
    """

    DOC_TYPES = ["readme", "architecture", "api", "retrospective", "onboarding"]

    def __init__(self, generation: int = 1, ghost: dict | None = None):
        super().__init__(
            agent_id=str(uuid.uuid4()),
            name="DocWriter",
            district="projects",
            generation=generation,
        )
        self.capabilities = ["documentation", "project", "write"]
        if ghost:
            self.inherit_ghost(ghost)
        self._memory = EpisodicMemory()
        self._obsidian = ObsidianSync()
        self._context = ContextEngine()
        logger.info(f"[VECTOR][doc_writer] ready gen={generation}")

    def _generate_doc(self, project_name: str, doc_type: str, context: str, hydration: str) -> str | None:
        """Returns the generated doc, or None when the LLM failed (never a
        canned placeholder that would be written to the vault as a real doc)."""
        templates = {
            "readme": (
                f"Write a README.md for project: {project_name}\n\n"
                f"Context:\n{context}\n\n"
                "Include: ## Overview, ## Features, ## Installation, ## Usage, ## Tech Stack"
            ),
            "architecture": (
                f"Write an architecture doc for: {project_name}\n\n"
                f"Context:\n{context}\n\n"
                "Include: ## System Overview, ## Components, ## Data Flow, ## Key Decisions, ## Trade-offs"
            ),
            "api": (
                f"Write API documentation for: {project_name}\n\n"
                f"Context:\n{context}\n\n"
                "Include: ## Endpoints, ## Request/Response formats, ## Authentication, ## Error codes"
            ),
            "retrospective": (
                f"Write a project retrospective for: {project_name}\n\n"
                f"Context:\n{context}\n\n"
                "Include: ## What went well, ## What didn't, ## Lessons learned, ## Action items"
            ),
            "onboarding": (
                f"Write an onboarding guide for new contributors to: {project_name}\n\n"
                f"Context:\n{context}\n\n"
                "Include: ## Prerequisites, ## Setup steps, ## Key concepts, ## First task suggestions"
            ),
        }
        prompt = templates.get(doc_type, templates["readme"])

        try:
            from core.inference.vectorcode_llm import chat
            text = chat(model=_REASONING, messages=[{"role": "system", "content": hydration}, {"role": "user", "content": prompt}], timeout=60.0)
            if not text:
                raise ValueError("empty response")
            return text
        except Exception as e:
            logger.warning("[VECTOR][doc_writer] LLM unavailable: {}", e)
            return None

    def write_doc(self, project_name: str, doc_type: str, context: str = "") -> bool:
        """
        Generate and write a project document.
        doc_type: readme | architecture | api | retrospective | onboarding
        """
        if doc_type not in self.DOC_TYPES:
            logger.warning(f"[VECTOR][doc_writer] unknown doc_type: {doc_type}")
            return False

        safe_name = safe_note_title(project_name)
        if not safe_name:
            logger.warning("[VECTOR][doc_writer] empty/invalid project name: {!r}", project_name)
            return False

        hydration = self._context.session_hydration_prompt()
        content = self._generate_doc(project_name, doc_type, context, hydration)
        if content is None:
            logger.error("[VECTOR][doc_writer] no doc written for {} ({}): generation failed", project_name, doc_type)
            self.deduct_points(5, "doc generation failed")
            return False

        date_str = datetime.date.today().isoformat()
        title = f"{safe_name} — {doc_type.title()}"

        try:
            self._obsidian.write_note(
                title=title,
                content=f"# {title}\n\n*Generated: {date_str}*\n\n{content}\n\n---\n*auto-generated by DocWriter*",
                folder="Projects",
                tags=["project", "documentation", doc_type, "vector"],
            )
            self._memory.store(
                event_type="doc_written",
                content=f"Doc written: {title}",
                tags=["projects", "documentation", doc_type],
                source="doc_writer",
            )
            self._memory.store_chain(
                situation=f"doc_writing_{doc_type}",
                goal_ids=["project_documentation"],
                steps=["llm_generate", "obsidian_write"],
                action="write_doc",
                outcome=f"{doc_type} written for {project_name}",
                reward=0.8,
            )
            self.award_points(30, f"doc: {title}")
            logger.info(f"[VECTOR][doc_writer] written: {title}")
            return True
        except Exception as e:
            logger.error(f"[VECTOR][doc_writer] write failed: {e}")
            self.deduct_points(5, "write failed")
            return False

    async def answer_projects_question(self, query: str) -> str:
        """Answer a free-text question instead of silently writing a new
        (context-free, since no real project/doc_type was given) 'VECTOR
        readme' note into the vault on every unmatched call — a real,
        unrelated file-write side effect for a stray conversational
        message (KNOWN_ISSUES bug pattern)."""
        context = f"DocWriter generates: {', '.join(self.DOC_TYPES)} docs, written to the Projects vault folder."
        prompt = (
            "You are VECTOR's DocWriter in the projects district. Answer "
            "the owner's question using this real context — do not invent "
            f"data you don't have:\n\n{context}\n\nQuestion: {query}"
        )
        try:
            result = self.vchat([{"role": "user", "content": prompt}])
            return (result or "").strip() or context
        except Exception as e:
            logger.warning(f"[VECTOR][doc_writer] answer_projects_question failed: {e}")
            return context

    async def run(self, task: dict) -> dict:
        p = task.get("params") or {}
        query = (
            p.get("query")
            or task.get("query")
            or task.get("text")
            or ""
        ).strip()
        if query and not p.get("project") and not p.get("doc_type"):
            answer = await self.answer_projects_question(query)
            if answer:
                return {"status": "ok", "response": answer}

        ok = self.write_doc(p.get("project", "VECTOR"), p.get("doc_type", "readme"), p.get("context", ""))
        return {"status": "ok" if ok else "error"}

    async def run_forever(self) -> None:
        logger.info("[VECTOR][doc_writer] run_forever — event-driven (write_doc calls)")
        while self.is_alive:
            try:
                await asyncio.sleep(60)
            except Exception as e:
                logger.error(f"[VECTOR][doc_writer] tick: {e}")
        logger.warning("[VECTOR][doc_writer] died — HP=0")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    import tempfile

    bot = DocWriter()
    assert bot.health_points == 500
    with tempfile.TemporaryDirectory() as d:
        vault = Path(d)
        (vault / "Projects").mkdir()
        bot._obsidian._vault = vault
        ok = bot.write_doc(
            "VECTOR",
            "readme",
            context="VECTOR is an autonomous AI agent system for personal productivity.",
        )
    assert ok
    print(f"OK doc_writer.py HP={bot.health_points} ok={ok}")
