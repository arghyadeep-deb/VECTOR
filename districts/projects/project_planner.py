import sys
import uuid
import asyncio
import datetime
from pathlib import Path

from core.config import CONFIG
from core.city.agent_base import AgentBase
from core.memory.episodic import EpisodicMemory
from core.memory.obsidian_sync import ObsidianSync
from core.loop.context_engine import ContextEngine
from loguru import logger

_REASONING = CONFIG["models"]["reasoning"]


class ProjectPlanner(AgentBase):
    """
    Creates and manages project plans stored in episodic/semantic memory
    and written to Obsidian. Decomposes goals into milestones and tasks.
    RULE 11: vector-reasoning (local), not Claude API.
    """

    def __init__(self, generation: int = 1, ghost: dict | None = None):
        super().__init__(
            agent_id=str(uuid.uuid4()),
            name="ProjectPlanner",
            district="projects",
            generation=generation,
        )
        if ghost:
            self.inherit_ghost(ghost)
        self._memory = EpisodicMemory()
        self._obsidian = ObsidianSync()
        self._context = ContextEngine()
        logger.info(f"[VECTOR][project_planner] ready gen={generation}")

    def _generate_plan(self, name: str, goal: str, deadline: str, hydration: str) -> str:
        prompt = (
            f"Create a detailed project plan for: {name}\n"
            f"Goal: {goal}\n"
            f"Deadline: {deadline}\n\n"
            "Structure the plan as:\n"
            "## Objective\n"
            "## Milestones\n(3-5 milestones with dates)\n"
            "## Tasks\n(Bulleted task list under each milestone)\n"
            "## Risks\n(Top 3 risks and mitigations)\n"
            "## Success Criteria\n"
            "Be specific, realistic, and concise."
        )
        try:
            from core.inference.vectorcode_llm import chat
            from core.prompt_library import get_library as _gl
            _lib = _gl().get_for_agent("project_planner") or ""
            _sys = (hydration + "\n\n" + _lib).strip() if _lib else hydration
            text = chat(model=_REASONING, messages=[{"role": "system", "content": _sys}, {"role": "user", "content": prompt}], timeout=60.0)
            if not text:
                raise ValueError("empty response")
            return text
        except Exception as e:
            logger.warning(f"[VECTOR][project_planner] LLM unavailable: {e}")
            return f"## Objective\n{goal}\n\n## Deadline\n{deadline}\n\n*Plan generation unavailable.*"

    def create_project(self, name: str, goal: str, deadline: str) -> dict:
        """Create a new project plan. Returns project dict."""
        project_id = str(uuid.uuid4())[:8]
        hydration = self._context.session_hydration_prompt()
        plan = self._generate_plan(name, goal, deadline, hydration)

        self._memory.store(
            event_type="project_created",
            content=f"Project: {name} | Goal: {goal[:80]} | Deadline: {deadline}",
            tags=["projects", "planning", name.lower().replace(" ", "_")],
            source="project_planner",
        )
        self._memory.remember(
            key=f"project:{project_id}",
            value=f"{name}|{goal}|{deadline}",
            category="active_project",
            confidence=0.95,
        )

        try:
            self._obsidian.write_note(
                title=f"Project — {name}",
                content=(
                    f"# Project — {name}\n\n"
                    f"**ID:** {project_id}\n"
                    f"**Deadline:** {deadline}\n"
                    f"**Created:** {datetime.date.today().isoformat()}\n\n"
                    f"{plan}\n\n"
                    f"---\n*auto-generated by ProjectPlanner*"
                ),
                folder="Projects",
                tags=["project", "planning", "vector"],
            )
        except Exception as e:
            logger.warning(f"[VECTOR][project_planner] obsidian write failed: {e}")

        self.award_points(40, f"project created: {name}")
        logger.info(f"[VECTOR][project_planner] created: {name} (id={project_id})")
        return {"id": project_id, "name": name, "goal": goal, "deadline": deadline, "plan": plan}

    def list_active_projects(self) -> list[dict]:
        try:
            cur = self._memory.conn.cursor()
            cur.execute(
                "SELECT key, value, updated_at FROM semantic_memory "
                "WHERE category = 'active_project' ORDER BY updated_at DESC LIMIT 20"
            )
            cols = [d[0] for d in cur.description]
            rows = [dict(zip(cols, r)) for r in cur.fetchall()]
            projects = []
            for r in rows:
                parts = r["value"].split("|")
                projects.append({
                    "id": r["key"].replace("project:", ""),
                    "name": parts[0] if len(parts) > 0 else "?",
                    "goal": parts[1] if len(parts) > 1 else "?",
                    "deadline": parts[2] if len(parts) > 2 else "?",
                    "created": (r["updated_at"] or "")[:10],
                })
            return projects
        except Exception as e:
            logger.warning(f"[VECTOR][project_planner] list failed: {e}")
            return []

    async def answer_projects_question(self, query: str) -> str:
        """Answer a free-text question grounded in the real active-project
        list, instead of silently no-op'ing with a bare agent-name echo
        regardless of what was actually asked (KNOWN_ISSUES bug pattern)."""
        try:
            projects = self.list_active_projects()
            if projects:
                names = ", ".join(proj["name"] for proj in projects[:10])
                context = f"{len(projects)} active project(s): {names}."
            else:
                context = "No active projects tracked right now."
        except Exception:
            context = "Active project list unavailable right now."
        prompt = (
            "You are VECTOR's ProjectPlanner in the projects district. "
            "Answer the owner's question using this real context — do not "
            f"invent data you don't have:\n\n{context}\n\nQuestion: {query}"
        )
        try:
            result = self.vchat([{"role": "user", "content": prompt}])
            return (result or "").strip() or context
        except Exception as e:
            logger.warning(f"[VECTOR][project_planner] answer_projects_question failed: {e}")
            return context

    async def run(self, task: dict) -> dict:
        p = task.get("params", {})
        if task.get("type") == "create_project":
            result = self.create_project(p.get("name", ""), p.get("goal", ""), p.get("deadline", ""))
            return {"status": "ok", **result}

        query = (
            p.get("query")
            or task.get("query")
            or task.get("text")
            or ""
        ).strip()
        if query:
            answer = await self.answer_projects_question(query)
            if answer:
                return {"status": "ok", "response": answer}

        return {"status": "ok", "agent": self.name}

    async def run_forever(self) -> None:
        logger.info("[VECTOR][project_planner] run_forever — event-driven (create_project calls)")
        while self.is_alive:
            try:
                await asyncio.sleep(60)
            except Exception as e:
                logger.error(f"[VECTOR][project_planner] tick: {e}")
        logger.warning("[VECTOR][project_planner] died — HP=0")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    import tempfile

    bot = ProjectPlanner()
    assert bot.health_points == 500
    with tempfile.TemporaryDirectory() as d:
        vault = Path(d)
        (vault / "Projects").mkdir()
        bot._obsidian._vault = vault
        proj = bot.create_project("VECTOR Phase 2", "Complete all Phase 2 districts", "2026-06-01")
    assert proj["id"]
    assert proj["name"] == "VECTOR Phase 2"
    projects = bot.list_active_projects()
    print(f"OK project_planner.py HP={bot.health_points} id={proj['id']} active={len(projects)}")
